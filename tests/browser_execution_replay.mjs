import assert from "node:assert/strict";
import fs from "node:fs/promises";
import {spawn} from "node:child_process";
import {chromium} from "playwright";

const s=spawn("python3",["-m","tests.saas_fixture_server"],{stdio:["ignore","pipe","pipe"]});
let base="";
let stderr="";
s.stdout.on("data",b=>{const m=b.toString().match(/REFIT_FIXTURE_READY=(\{[^\n]+\})/);if(m)base=JSON.parse(m[1]).url;});
s.stderr.on("data",b=>{stderr+=b.toString();});
let browser;
try {
 for(let i=0;i<150&&!base;i++)await new Promise(r=>setTimeout(r,100));
 assert.ok(base,"SaaS fixture failed to start: "+stderr.slice(-600));
 await fs.mkdir("artifacts/replay-demo",{recursive:true});
 browser=await chromium.launch();
 const page=await browser.newPage({viewport:{width:1920,height:1080},ignoreHTTPSErrors:true,recordVideo:{dir:"artifacts/replay-demo",size:{width:1920,height:1080}}});
 const errors=[],actions=[];
 page.on("pageerror",e=>errors.push(e.message));
 page.on("request",r=>{if(r.method()==="POST"&&r.url().includes("/api/application/"))actions.push(r.url());});
 await page.goto(base+"/app",{waitUntil:"domcontentloaded"});
 await page.getByRole("link",{name:/Watch agent execution/}).waitFor({state:"visible"});
 await page.getByRole("link",{name:/Watch agent execution/}).click();
 await page.locator("#replayScreen").waitFor({state:"visible"});
 assert.equal(new URL(page.url()).pathname,"/app/replay");
 const recorded=await page.request.get(base+"/api/application/demo");
 assert.equal(recorded.status(),200);
 const data=await recorded.json();
 const allowed=new Set(["run_started","runtime_ready","phase_started","phase_completed","sandbox_started","sandbox_cleanup","inference_requested","inference_completed","case_completed","terminal"]);
 const expected=data.events.filter(e=>allowed.has(e.type)).length;
 assert.ok(expected>=12,"No substantial real run was loaded");
 const shown=await page.locator("[data-replay-index]").count();
 assert.equal(shown,expected,"Replay must show only recorded event count");
 await page.screenshot({path:"artifacts/replay-demo/replay-opening.png"});
 await page.getByRole("button",{name:"Play recorded execution"}).click();
 await page.waitForFunction(()=>document.querySelector("#replayProgress")?.textContent.trim().startsWith("2 /"),null,{timeout:6000});
 await page.locator("[data-replay-index='7']").click();
 assert.equal(await page.locator("#replayProgress").textContent(),"8 / "+expected);
 await page.locator("#replayScrub").evaluate((el,v)=>{el.value=String(v);el.dispatchEvent(new Event("input",{bubbles:true}));},expected-1);
 assert.ok((await page.locator("#replayProgress").textContent()).startsWith(expected+" /"));
 await page.locator("#replayScrub").evaluate(el=>{el.value="0";el.dispatchEvent(new Event("input",{bubbles:true}));});
 await page.locator("#replaySpeed").selectOption("4");
 await page.locator("#replayPlay").click();
 await page.waitForFunction(()=>document.querySelector("#replayProgress")?.textContent.trim().startsWith("2 /"),null,{timeout:4000});
 await page.screenshot({path:"artifacts/replay-demo/replay-playing.png"});
 assert.equal(actions.length,0,"Read-only replay must never invoke a billable POST");
 assert.deepEqual(errors,[],"Browser console errors");
 await page.goto(base+"/app/replay",{waitUntil:"domcontentloaded"});
 await page.locator("#replayScreen").waitFor({state:"visible"});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:"artifacts/replay-demo/replay-mobile.png"});
 console.log(JSON.stringify({result:"passed",source:"recorded archival agent run",events:expected,requested_inference:0,desktop:true,mobile:true}));
 await page.close();
}finally{
 await browser?.close();
 s.kill("SIGKILL");
}
