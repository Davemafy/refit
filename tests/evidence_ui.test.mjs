import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {gunzipSync} from "node:zlib";
import vm from "node:vm";
const app=readFileSync("web/application/app.js","utf8");
const start=app.indexOf("function evidenceEntries(");
const stop=app.indexOf("function runLog(",start);
assert.ok(start>0&&stop>start);
const state={evidenceItems:[],evidenceSelected:null};
const safe=value=>String(value??"").replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
const context=vm.createContext({state,safe});
vm.runInContext(app.slice(start,stop),context);
const fixture=JSON.parse(gunzipSync(readFileSync("data/evaluations/application-browser-generic-2026-11-07.json.gz")));
const run=fixture.run,events=fixture.events;
const entries=vm.runInContext("evidenceEntries",context)(run,events);
assert.equal(entries.filter(x=>x.type==="verification").length,run.verification.length);
assert.equal(entries.filter(x=>x.type==="case").length,events.filter(x=>x.type==="case_completed").length);
assert.equal(entries.filter(x=>x.type==="cleanup").length,events.filter(x=>x.type==="sandbox_cleanup").length);
assert.equal(entries.at(-1).type,"provenance");
const explorer=vm.runInContext("evidenceExplorer",context)(run,events);
assert.match(explorer,/evidence-workspace/);
assert.match(explorer,/evidence-inspector/);
assert.match(explorer,/aria-pressed="true"/);
assert.match(explorer,/Fresh export check/);
assert.match(explorer,/magnetic-divergence/);
assert.match(explorer,/Sandbox cleanup/);
const detail=vm.runInContext("evidenceDetail",context);
assert.match(detail(entries.find(x=>x.type==="cleanup")) ,/Cleanup reason/);
assert.match(detail(entries.find(x=>x.type==="case")) ,/Tool observations/);
assert.match(detail(entries.at(-1)),/Source model/);
const hostile={key:"case-x",type:"case",title:'<script>alert("x")</script>',subtitle:"Train",details:{case:"<img src=x onerror=alert(1)>"}};
const escaped=detail(hostile);
assert.doesNotMatch(escaped,/<script>|<img/);
assert.match(escaped,/&lt;script&gt;/);
const unknown={key:"case-z",type:"case",title:"Missing case",subtitle:"Train",details:{}};
assert.match(detail(unknown),/Not recorded/);
console.log(JSON.stringify({status:"pass",type:"evidence_inspector",observations:entries.length,verification:run.verification.length,cases:events.filter(x=>x.type==="case_completed").length,cleanup:events.filter(x=>x.type==="sandbox_cleanup").length}));
